"""Build every historical-dataset artifact from the frozen raw source.

Usage:
    python -m fantasyprep.historical.dataset.build

Writes:
    data/historical/player_seasons.parquet          canonical player x season
    data/historical/player_season_features.parquet  + ranks, rates, prior-season lags
    data/historical/outcome_bucket_study.json       bucket-width research output
    docs/HISTORICAL_DATA_AUDIT.md                   the audit report

Deterministic: same input file in, byte-identical outputs out. Nothing here
touches the simulator, the decision engine, or the backtest.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

from fantasyprep.historical.dataset import audit as audit_mod
from fantasyprep.historical.dataset import distributions as dist_mod
from fantasyprep.historical.dataset.canonical import build_canonical, skill_players
from fantasyprep.historical.dataset.features import (
    PRE_SEASON_COLUMNS,
    add_features,
    outcome_columns,
)
from fantasyprep.historical.dataset.loader import DEFAULT_CSV_PATH, CsvPlayerSeasonSource
from fantasyprep.historical.dataset.metadata import add_metadata, coverage_report
from fantasyprep.historical.dataset.ranks import MIN_GAMES_FOR_PPG_RANK, add_ranks

DEFAULT_OUT_DIR = Path("data/historical")
DEFAULT_DOCS_DIR = Path("docs")


def build_all(
    csv_path: Path = DEFAULT_CSV_PATH,
    out_dir: Path = DEFAULT_OUT_DIR,
    docs_dir: Path = DEFAULT_DOCS_DIR,
    with_metadata: bool = True,
) -> dict:
    source = CsvPlayerSeasonSource(csv_path)
    out_dir.mkdir(parents=True, exist_ok=True)
    docs_dir.mkdir(parents=True, exist_ok=True)

    print(f"Auditing {csv_path}...")
    findings = audit_mod.audit_all(source)

    print("Building canonical player-season table...")
    canonical = build_canonical(source)

    print("Adding ranks and derived features...")
    # Ranks are computed on the skill-position pool only: "the WR12 season" means
    # 12th among receivers, and a pool containing punters would be meaningless.
    skill = add_ranks(skill_players(canonical))
    features = add_features(skill)

    if with_metadata:
        print("Joining player metadata (age, experience, draft capital)...")
        features = add_metadata(features)
        metadata_coverage = coverage_report(features)
        print(f"  age coverage: {metadata_coverage['age_coverage']:.1%}")
    else:
        metadata_coverage = None

    print("Running outcome bucket study...")
    adp_pairs = dist_mod.adp_rank_pairs(skill)
    adp_meta = adp_pairs.pop("_meta")
    adp_study = dist_mod.bucket_study(adp_pairs)
    prior_pairs = dist_mod.prior_rank_pairs(features)
    prior_study = dist_mod.bucket_study(prior_pairs)

    study = {
        "adp_rank_buckets": {
            "description": "Draft-time FFC positional ADP rank vs actual points, our scoring.",
            "seasons_used": adp_meta["seasons_used"],
            "seasons_skipped_no_adp_cache": adp_meta["seasons_skipped"],
            "buckets": adp_study,
            "width_comparison": dist_mod.width_comparison(adp_study),
        },
        "prior_finish_rank_buckets": {
            "description": "Prior-season positional finish rank vs actual points, our scoring.",
            "seasons_used": sorted(
                int(s) for s in features.dropna(subset=["prev_position_rank"])["season"].unique()
            ),
            "buckets": prior_study,
            "width_comparison": dist_mod.width_comparison(prior_study),
        },
    }

    canonical_path = out_dir / "player_seasons.parquet"
    features_path = out_dir / "player_season_features.parquet"
    study_path = out_dir / "outcome_bucket_study.json"
    audit_path = docs_dir / "HISTORICAL_DATA_AUDIT.md"

    canonical.to_parquet(canonical_path, index=False)
    features.to_parquet(features_path, index=False)
    study_path.write_text(json.dumps(study, indent=2, sort_keys=True), encoding="utf-8")
    audit_path.write_text(
        render_audit(findings, canonical, features, study, csv_path, metadata_coverage),
        encoding="utf-8",
    )

    print(f"\n  {canonical_path}  ({len(canonical):,} rows x {len(canonical.columns)} cols)")
    print(f"  {features_path}  ({len(features):,} rows x {len(features.columns)} cols)")
    print(f"  {study_path}")
    print(f"  {audit_path}")
    return {
        "canonical": canonical, "features": features, "study": study,
        "audit": findings, "metadata_coverage": metadata_coverage,
    }


def render_audit(
    findings: dict, canonical: pd.DataFrame, features: pd.DataFrame, study: dict,
    csv_path: Path, metadata_coverage: dict | None = None,
) -> str:
    coverage = findings["coverage"]
    identity = findings["identity"]
    scoring = findings["scoring"]
    missing = findings["missingness"]
    eras = findings["era_gaps"]

    lines: list[str] = []
    add = lines.append

    add("# Historical Data Audit")
    add("")
    add("Generated by `python -m fantasyprep.historical.dataset.build`. Every number")
    add("below is computed from the raw file at build time, not transcribed by hand --")
    add("re-run the build to refresh it.")
    add("")
    add("## Source")
    add("")
    add(f"- **Path**: `{csv_path.as_posix()}` (immutable -- never written to)")
    add(f"- **Rows**: {coverage['total_rows']:,} across {coverage['columns']} columns")
    add("- **Upstream**: nflverse seasonal player stats. This is the *same source* the live")
    add("  pipeline already pulls via `nfl_data_py.import_seasonal_data`")
    add("  (`historical/sources/nfl_stats.py`). Its value-add is the extra 1999-2009")
    add("  seasons, and being frozen -- live pulls drift as nflverse revises data.")
    add("")

    add("## Two traps in the raw file")
    add("")
    add("Both would corrupt anything built on this data, and neither is visible after")
    add("the fact. They're the reason `loader.py` exists rather than a bare `read_csv`.")
    add("")
    add("### 1. `season_type` triple-counts every player-season")
    add("")
    add("The file holds three *views of the same seasons*, not three sets of players:")
    add("")
    add("| season_type | rows |")
    add("|---|---|")
    for key, value in sorted(coverage["season_type_counts"].items()):
        add(f"| `{key}` | {value:,} |")
    add("")
    add(
        f"`REG+POST` overlaps `REG` on {identity['reg_plus_post_overlap_rows']:,} player-seasons "
        f"and reports **different** fantasy points for "
        f"**{identity['reg_plus_post_disagreements']:,}** of them."
    )
    add("Reading the file unfiltered inflates season totals with playoff production.")
    add(f"We keep `REG` only: **{coverage['reg_rows']:,} rows**, matching the existing")
    add("pipeline's `s_type=\"REG\"`.")
    add("")
    add("### 2. Air-yards columns are fabricated zeros before 2006, not nulls")
    add("")
    add(
        f"nflfastR's air-yards charting begins in {eras['era_start']}. Before that, these "
        "columns are *zero*, so they pass a null check while containing no information. "
        "A model trained across the full history would learn that nobody had air yards "
        "in 2003."
    )
    add("")
    add("| column | pre-2006 null | pre-2006 nonzero | post-2006 nonzero | pre-2006 max | post-2006 max |")
    add("|---|---|---|---|---|---|")
    for column, stats in eras["columns"].items():
        add(
            f"| `{column}` | {stats['pre_2006_null_frac']:.0%} | "
            f"{stats['pre_2006_nonzero_frac']:.1%} | {stats['post_2006_nonzero_frac']:.1%} | "
            f"{stats['pre_2006_max']} | {stats['post_2006_max']} |"
        )
    add("")
    add("`receiving_yards_after_catch` is the subtlest case: it isn't uniformly zero")
    add("pre-2006, it's *fragmentary* -- a handful of players per season with a season")
    add("maximum an order of magnitude below the 2006 figure. That's partial charting,")
    add("not real production, and it's more dangerous than an honest zero because it")
    add("looks alive. `loader.mask_uncollected_eras` converts all of these to NaN.")
    add("")

    add("## Coverage")
    add("")
    add(
        f"- **Seasons**: {coverage['earliest_season']}-{coverage['latest_season']} "
        f"({coverage['n_seasons']} seasons, no gaps)"
    )
    add(f"- **Regular-season rows**: {coverage['reg_rows']:,}")
    add(
        f"- **Regular-season rows at QB/RB/WR/TE**: {coverage['reg_skill_rows']:,} "
        f"({coverage['unique_players_reg_skill']:,} unique players)"
    )
    add(f"- **Unique player_ids (all positions)**: {coverage['unique_players']:,}")
    add("")
    add("### Rows by position (regular season)")
    add("")
    add("| position | rows |")
    add("|---|---|")
    for position, count in sorted(
        coverage["position_counts"].items(), key=lambda kv: -kv[1]
    ):
        add(f"| {position} | {count:,} |")
    add("")
    add(
        "Non-skill positions (punters, linemen, defensive backs with a return "
        "touchdown or an emergency carry) are retained in the canonical table so "
        "coverage reporting stays honest; ranks and distributions filter to "
        "QB/RB/WR/TE. **FB and HB are mapped to RB** in a separate "
        "`fantasy_position` column -- the source `position` is never overwritten, "
        "so the mapping stays reversible."
    )
    add("")
    add("### Rows by season x position (QB/RB/WR/TE)")
    add("")
    add("| season | QB | RB | TE | WR | total |")
    add("|---|---|---|---|---|---|")
    for season in sorted(coverage["rows_by_season_position"]):
        row = coverage["rows_by_season_position"][season]
        counts = [row.get(p, 0) for p in ("QB", "RB", "TE", "WR")]
        add(f"| {season} | " + " | ".join(str(c) for c in counts) + f" | {sum(counts)} |")
    add("")

    add("## Identity")
    add("")
    add(
        f"- `player_id` is the nflverse GSIS id (format `{identity['id_format_example']}`) -- "
        "the same id space as `import_weekly_data`, `import_players`, and "
        "`import_ids`, so future joins to weekly data and player metadata need "
        "**no fuzzy name matching**."
    )
    add(
        f"- **Stable across seasons**: {identity['players_in_multiple_seasons']:,} players "
        f"appear in more than one season, up to {identity['max_seasons_for_one_player']} "
        "seasons for a single id."
    )
    add(
        f"- **Duplicate (player_id, season) rows after the REG filter: "
        f"{identity['duplicate_player_season_rows_reg']}.** One row per player-season, "
        "confirmed rather than assumed. `loader.load_regular_season` raises if this "
        "ever stops being true instead of silently de-duplicating."
    )
    add(
        f"- **Name columns**: `player_name` is "
        f"{identity['player_name_null_frac']:.0%} null and unusable; "
        f"`player_display_name` is {identity['player_display_name_null_frac']:.0%} null "
        "and is the real name column. The loader substitutes it."
    )
    if identity["unnamed_reg_rows"]:
        example = identity["unnamed_examples"][0]
        add(
            f"- **{identity['unnamed_reg_rows']} orphan row(s) have no name *and* no "
            f"position** (e.g. `{example['player_id']}`, {example['season']}, "
            f"{example['recent_team']}, {example['games']} games) and are dropped by the "
            f"loader -- unjoinable to ADP and unrankable. This is reported rather than "
            f"silent, and the loader still fails outright if unnamed rows ever exceed "
            f"0.1% of the file, so a systemic name-resolution failure can't slip "
            f"through as a rounding error. Canonical row count is therefore "
            f"{len(canonical):,}, not {coverage['reg_rows']:,}."
        )
    add(
        f"- **Team changes do not create duplicate rows** "
        f"(max distinct `recent_team` per player-season: "
        f"{identity['teams_per_player_season_max']}). A traded player has one row "
        "carrying his *last* team. **Limitation**: team-split season lines are not "
        "recoverable from this file, so any future team-context feature (offensive "
        "environment, pace, target competition) needs the weekly data instead."
    )
    add("")

    add("## Fantasy-point validation")
    add("")
    add(
        "The source's `fantasy_points_ppr` column was **not** assumed to mean what its "
        "name suggests. We reproduced it with our own scoring function at candidate "
        f"passing-TD values across all {scoring['n_rows_checked']:,} regular-season "
        "skill-position rows:"
    )
    add("")
    add("| our scoring variant | max abs delta | mean abs delta | rows off by >0.5 | exact match |")
    add("|---|---|---|---|---|")
    for label, stats in scoring["variants"].items():
        add(
            f"| `{label}` | {stats['max_abs_delta']} | {stats['mean_abs_delta']} | "
            f"{stats['rows_over_half_point']:,} | "
            f"{'**yes**' if stats['exact_match'] else 'no'} |"
        )
    add("")
    add(
        "**Conclusion: the source column is full PPR with 4-point passing touchdowns.** "
        "Our league uses 6. The reproduction at `pass_td=4.0` is exact to 0.00 across "
        "every row, which is a strong independent validation of "
        "`nfl_stats.compute_points` itself -- the same function the live pipeline and "
        "the backtest score with."
    )
    add("")
    add("Under our real settings the largest gaps are all quarterbacks, exactly as expected:")
    add("")
    add("| player | season | pos | pass TDs | ours (6pt TD) | source (4pt TD) | delta |")
    add("|---|---|---|---|---|---|---|")
    for example in scoring["worked_examples"]:
        add(
            f"| {example['player']} | {example['season']} | {example['position']} | "
            f"{example['passing_tds']} | {example['our_points_6pt_td']} | "
            f"{example['source_fantasy_points_ppr']} | {example['delta']:+} |"
        )
    add("")
    add(
        f"Each delta is exactly `2 x passing_tds`. Across all rows our scoring differs "
        f"from the source's by a mean of {scoring['our_scoring_mean_abs_delta']} points, "
        f"with {scoring['rows_over_two_points']:,} rows differing by more than 2."
    )
    add("")
    add(
        "**Therefore `fantasy_points_ppr` is kept only as "
        "`fantasy_points_nflverse_ppr`, a cross-check column. It is never the outcome "
        "variable.** `fantasy_points` in the canonical table is computed under this "
        "league's real settings."
    )
    add("")

    add("## Missingness")
    add("")
    add(
        "Regular-season QB/RB/WR/TE rows. **Nothing is imputed anywhere in this "
        "pipeline** -- missing values stay NaN, and every derived ratio returns NaN "
        "rather than 0 when its denominator is zero."
    )
    add("")
    add("| column | null % |")
    add("|---|---|")
    for column, frac in sorted(missing["overall_null_frac"].items(), key=lambda kv: -kv[1]):
        add(f"| `{column}` | {frac:.1%} |")
    add("")
    add("Reading the non-obvious ones:")
    add("")
    add(
        "- `passing_epa` ~81% null is **by design**, not a defect: only quarterbacks "
        "throw. Same for `pacr`/`dakota`."
    )
    add(
        "- `target_share` ~16% null covers players with no team-target denominator in "
        "that season (almost all quarterbacks)."
    )
    add(
        "- `air_yards_share` / `wopr` are 100% null pre-2006 *after* era masking, which "
        "is the honest figure. Before masking they read as 0% null -- see trap 2."
    )
    add("")
    add("### Null rate by season, selected columns")
    add("")
    add("| season | target_share | air_yards_share | wopr | receiving_epa |")
    add("|---|---|---|---|---|")
    for season in sorted(missing["null_frac_by_season"]):
        row = missing["null_frac_by_season"][season]
        add(
            f"| {season} | {row.get('target_share', 0):.1%} | "
            f"{row.get('air_yards_share', 0):.1%} | {row.get('wopr', 0):.1%} | "
            f"{row.get('receiving_epa', 0):.1%} |"
        )
    add("")
    add(
        "The 2006 cliff in `air_yards_share`/`wopr` is the era boundary, not a data "
        "quality problem -- but any model spanning it must treat pre-2006 as a "
        "different feature regime rather than pooling."
    )
    add("")

    add("## Canonical tables")
    add("")
    add(f"### `data/historical/player_seasons.parquet`")
    add("")
    add(
        f"{len(canonical):,} rows x {len(canonical.columns)} columns, one row per "
        "`player_id x season`."
    )
    add("")
    add("| column | meaning |")
    add("|---|---|")
    add("| `player_id` | nflverse GSIS id; stable join key |")
    add("| `player_name` | from `player_display_name` |")
    add("| `season` | regular season year |")
    add("| `position` | source position, unmodified |")
    add("| `fantasy_position` | `position` with FB/HB mapped to RB |")
    add("| `position_group` | source position group |")
    add("| `recent_team` | last team of the season (see Identity limitation) |")
    add("| `games` | regular-season games played |")
    add("| `fantasy_points` | **our league scoring** (`compute_points`, 6pt pass TD) |")
    add("| `fantasy_points_per_game` | NaN when `games` is 0 |")
    add("| `fantasy_points_nflverse_ppr` | source column, 4pt pass TD -- cross-check only |")
    add(
        "| passing / rushing / receiving / EPA / share columns | passed through from "
        "source unmodified, except pre-2006 era masking |"
    )
    add("")
    add(f"### `data/historical/player_season_features.parquet`")
    add("")
    add(
        f"{len(features):,} rows x {len(features.columns)} columns -- QB/RB/WR/TE only, "
        "with ranks, per-game rates, efficiency ratios, and prior-season lags."
    )
    add("")
    add("**Ranking methodology.** Ranks are computed on `fantasy_points` under our")
    add("scoring, never the source column. Ties use `min` (two players tied for 5th are")
    add("both 5, next is 7). The pool is every player at that fantasy position who")
    add("recorded a regular season, not just drafted ones -- restricting to drafted")
    add("players would bias the replacement-level tail. PPG rank comes in two variants:")
    add("`position_rank_ppg` ranks everyone (a 2-game cameo can top it), and")
    add(f"`position_rank_ppg_qualified` ranks only players with >= {MIN_GAMES_FOR_PPG_RANK}")
    add("games, leaving the rest NaN. Both are kept because which is correct depends on")
    add("the question.")
    add("")

    if metadata_coverage:
        add("### Player metadata join (age, experience, draft capital)")
        add("")
        add(
            f"`nfl_data_py.import_players` joined on `gsis_id` -- which *is* our "
            f"`player_id`, so no fuzzy matching. **Age coverage: "
            f"{metadata_coverage['age_coverage']:.1%}** of "
            f"{metadata_coverage['rows']:,} rows; rookie season "
            f"{metadata_coverage['rookie_season_coverage']:.1%}."
        )
        add("")
        add("| position | n with age | mean | min | max |")
        add("|---|---|---|---|---|")
        for position in sorted(metadata_coverage["age_by_position"]):
            s = metadata_coverage["age_by_position"][position]
            add(f"| {position} | {s['n']:,} | {s['mean']} | {s['min']} | {s['max']} |")
        add("")
        add(
            f"Draft position is present for "
            f"{metadata_coverage['draft_pick_coverage']:.1%} of rows. **The remaining "
            f"{metadata_coverage['undrafted_share']:.1%} is not missing data** -- those "
            "players went undrafted, which is real signal, so it is encoded as an "
            "explicit `undrafted` flag with the pick left NaN rather than filled with a "
            "sentinel a model would read as 'pick 0'."
        )
        add("")
        add(
            "These columns are **leakage-safe without a lag**: a birth date and a draft "
            "slot are fixed facts, so age entering season Y is knowable before season Y. "
            "Note what is deliberately excluded -- the source's `years_of_experience` is "
            "a career-to-date figure reflecting *today* rather than the row's season, so "
            "it would leak; `seasons_since_rookie_year` is computed against the row's own "
            "season instead."
        )
        add("")

    add("## Leakage safety")
    add("")
    add(
        "The eventual point of this data is leakage-safe held-out backtests, so the "
        "pre-season / outcome split is enforced in code rather than by convention "
        "(`features.py`):"
    )
    add("")
    add(
        f"- **`PRE_SEASON_COLUMNS`** ({len(PRE_SEASON_COLUMNS & set(features.columns))} "
        "present here): identity, plus `prev_*` values and `seasons_of_history`. Legal "
        "model inputs for predicting that season."
    )
    add(
        f"- **Outcome columns** ({len(outcome_columns(features))}): everything else -- "
        "that season's own stats, rates, ranks and points. Target variables only."
    )
    add(
        "- The outcome set is defined as the *complement* of the pre-season set, not as "
        "a second hand-maintained list, so a newly added column is treated as an "
        "outcome until someone deliberately classifies it. It fails closed."
    )
    add("- `preseason_frame(df, season)` is the sanctioned way to build model inputs.")
    add("")
    add("Two classifications worth calling out as deliberate:")
    add("")
    add(
        "- **`recent_team` is an outcome.** A team is usually known in August, but this "
        "column holds the player's *last* team, so for anyone traded midseason it "
        "encodes information that didn't exist at draft time. `prev_recent_team` is "
        "the safe version."
    )
    add(
        "- **`yoy_fantasy_change` is an outcome**, despite reading like a feature: "
        "season Y's change is (Y minus Y-1) and therefore contains Y. The usable form "
        "is `prev_yoy_fantasy_change`."
    )
    add("")
    add(
        "Prior-season lags only ever carry a *strictly adjacent* season forward. A "
        "player who missed a full season gets NaN for his `prev_*` values rather than "
        "a two-year-old season quietly relabelled as \"last year\"; "
        "`seasons_of_history` preserves the fact that he has a past."
    )
    add("")

    add("## Outcome bucket study")
    add("")
    add(
        "Full numbers in `data/historical/outcome_bucket_study.json`. This measures "
        "whether `historical/outcomes.py`'s `BUCKET_WIDTH = 3` is justified. **No "
        "simulator parameter was changed** -- that needs its own A/B backtest."
    )
    add("")
    adp = study["adp_rank_buckets"]
    prior = study["prior_finish_rank_buckets"]
    add(
        f"- **(a) ADP-rank buckets**: seasons {min(adp['seasons_used'])}-"
        f"{max(adp['seasons_used'])}. Directly comparable to today's buckets. Limited "
        "to 2010+ because that is FFC ADP's coverage floor -- **the 1999-2009 seasons "
        "in this dataset have no market rank at all**, which is the single biggest "
        "gap and the subject of `HISTORICAL_ADP_RESEARCH.md`."
    )
    add(
        f"- **(b) Prior-finish-rank buckets**: seasons {min(prior['seasons_used'])}-"
        f"{max(prior['seasons_used'])}, all 26 years. Leakage-safe by construction and "
        "usable across the full history."
    )
    add("")
    add("### Width tradeoff, ADP-rank study")
    add("")
    add("| position | width | buckets | median n/bucket | min n | spread of bucket medians |")
    add("|---|---|---|---|---|---|")
    for position in ("QB", "RB", "TE", "WR"):
        for width_key, stats in adp["width_comparison"].get(position, {}).items():
            add(
                f"| {position} | {width_key.replace('width_', '')} | "
                f"{stats['n_buckets']} | {stats['median_samples_per_bucket']} | "
                f"{stats['min_samples_in_any_bucket']} | "
                f"{stats['spread_of_bucket_medians']} |"
            )
    add("")
    add(
        "Read it as the bias/variance trade it is: *median n/bucket* is the sampling "
        "stability a width buys, *spread of bucket medians* is the rank structure it "
        "retains. See `docs/` follow-ups and ROADMAP.md for the interpretation."
    )
    add("")

    add("## Known limitations")
    add("")
    add("1. **No market rank before 2010.** The dataset's 1999-2009 seasons cannot be")
    add("   bucketed by ADP at all. This is the binding constraint on using the extra")
    add("   history for anything ADP-conditioned.")
    add("2. **No age, birth date, draft position, or rookie year.** Not in this file at")
    add("   all -- see `PLAYER_METADATA_RESEARCH.md`.")
    add("3. **No team-split lines for traded players.** One row per player-season with")
    add("   the last team only.")
